def main() -> None:
    parser = argparse.ArgumentParser(description="Перенос треков из list.json в list_v2.json")
    parser.add_argument("--list", default=DEFAULT_LIST, help="путь к list.json (источник, не изменяется)")
    parser.add_argument("--list-v2", default=DEFAULT_LIST_V2, help="путь к list_v2.json (куда переносим)")
    parser.add_argument("--output", default=None, help="куда сохранить результат (по умолчанию перезаписывает --list-v2)")
    parser.add_argument("--cache", default=DEFAULT_CACHE, help="файл кеша длительностей url -> durationMs")
    parser.add_argument("--failed", default=DEFAULT_FAILED, help="куда сохранить список не обработанных треков")
    parser.add_argument("--workers", type=int, default=8, help="число параллельных загрузок (по умолчанию 8)")
    parser.add_argument("--timeout", type=float, default=30.0, help="таймаут одного запроса, сек")
    parser.add_argument("--limit", type=int, default=None, help="обработать только первые N новых треков (для теста)")
    parser.add_argument("--force", action="store_true", help="переобработать id, уже присутствующие в list_v2.json")
    parser.add_argument(
        "--dry-run", action="store_true",
        help="только показать распределение id по trackIds/tracks, без скачивания и без записи файла",
    )
    parser.add_argument(
        "--tolerance-ms", type=int, default=DEFAULT_TOLERANCE_MS,
        help=f"допуск (мс) при сравнении измеренной длительности с durationMs из Yandex Music API "
             f"(по умолчанию {DEFAULT_TOLERANCE_MS})",
    )
    parser.add_argument(
        "--api-batch-size", type=int, default=DEFAULT_API_BATCH_SIZE,
        help=f"сколько id запрашивать у Yandex Music API за один запрос (по умолчанию {DEFAULT_API_BATCH_SIZE})",
    )
    parser.add_argument(
        "--skip-api-check", action="store_true",
        help="не обращаться к Yandex Music API - все треки получат явный durationMs (старое поведение)",
    )
    args = parser.parse_args()
    args.output = args.output or args.list_v2

    with open(args.list, "r", encoding="utf-8") as f:
        source_data = json.load(f)
    tracks_map: dict = source_data.get("tracks") or {}
    if not tracks_map:
        sys.exit("В list.json не найдено треков (свойство 'tracks' пустое или отсутствует)")

    with open(args.list_v2, "r", encoding="utf-8") as f:
        list_v2 = json.load(f)

    storage = find_target_storage(list_v2)
    had_tracks_key = "tracks" in storage

    skip_ids = set() if args.force else already_migrated_ids(storage)
    todo = [(tid, url) for tid, url in tracks_map.items() if tid not in skip_ids]
    skipped_count = len(tracks_map) - len(todo)
    if skipped_count:
        print(f"Пропускаю {skipped_count} уже перенесённых id (используйте --force для переобработки)")

    if args.limit is not None:
        todo = todo[: args.limit]

    template_ids = [tid for tid, url in todo if last_url_segment(url) == tid]
    explicit_ids = [tid for tid, url in todo if last_url_segment(url) != tid]
    print(
        f"К обработке: {len(todo)} треков "
        f"({len(template_ids)} по шаблону urlTemplate, {len(explicit_ids)} с явной ссылкой)"
    )

    if not todo:
        print("Нечего переносить.")
        return
    if args.dry_run:
        print("--dry-run: скачивание, запрос Yandex Music API и запись файла пропущены")
        return

    if args.skip_api_check:
        print("--skip-api-check: сверка с Yandex Music API отключена, все треки получат явный durationMs")
        api_durations = {}
    else:
        print("Запрашиваю официальные длительности треков в Yandex Music API...")
        yandex_client = build_yandex_client()
        api_durations = fetch_api_durations(yandex_client, [tid for tid, _ in todo], args.api_batch_size)
        if not api_durations:
            print(
                "[!] Не получено ни одной длительности из Yandex Music API - "
                "все треки будут сохранены с явным durationMs",
                file=sys.stderr,
            )

    cache = DurationCache(args.cache)

    def worker(tid: str, url: str):
        cached = cache.get(url)
        if cached is not None:
            return cached
        duration_ms = fetch_duration_ms(url, args.timeout)
        cache.set(url, duration_ms)
        return duration_ms

    results = {}   # tid -> (url, duration_ms)
    failures = []  # (tid, url, error)
    total = len(todo)
    done = 0
    progress_lock = threading.Lock()

    executor = ThreadPoolExecutor(max_workers=args.workers)
    future_to_item = {executor.submit(worker, tid, url): (tid, url) for tid, url in todo}
    try:
        for future in as_completed(future_to_item):
            tid, url = future_to_item[future]
            with progress_lock:
                done += 1
                progress = f"[{done}/{total}]"
            try:
                duration_ms = future.result()
                results[tid] = (url, duration_ms)
                print(f"{progress} OK   id={tid} duration={duration_ms}ms")
            except Exception as e:
                failures.append((tid, url, str(e)))
                print(f"{progress} FAIL id={tid} url={url} error={e}", file=sys.stderr)
    except KeyboardInterrupt:
        print("\nПрервано пользователем, отменяю оставшиеся задачи и сохраняю то, что уже обработано...", file=sys.stderr)
        executor.shutdown(wait=False, cancel_futures=True)
    else:
        executor.shutdown(wait=True)

    trackIds = storage.setdefault("trackIds", [])
    tracks = storage.setdefault("tracks", {})
    matched_count = 0
    mismatched_count = 0
    for tid, (url, duration_ms) in results.items():
        api_duration_ms = api_durations.get(tid)
        is_match = api_duration_ms is not None and abs(duration_ms - api_duration_ms) <= args.tolerance_ms
        if is_match:
            matched_count += 1
        else:
            mismatched_count += 1

        if last_url_segment(url) == tid:
            trackIds.append(int(tid) if is_match else {"id": int(tid), "durationMs": duration_ms})
        else:
            tracks[tid] = url if is_match else {"url": url, "durationMs": duration_ms}

    # не оставляем пустой "tracks", если его не было и добавлять оказалось нечего
    if not had_tracks_key and not tracks:
        del storage["tracks"]

    if not args.skip_api_check:
        print(
            f"Сверка с Yandex Music API: совпало (голое значение) - {matched_count}, "
            f"разошлось/неизвестно (явный durationMs) - {mismatched_count}"
        )

    with open(args.output, "w", encoding="utf-8") as f:
        json.dump(list_v2, f, ensure_ascii=False, indent=4)
        f.write("\n")

    print(f"\nГотово: перенесено {len(results)} треков, ошибок: {len(failures)}")
    if failures:
        with open(args.failed, "w", encoding="utf-8") as f:
            json.dump(
                {tid: {"url": url, "error": err} for tid, url, err in failures},
                f, ensure_ascii=False, indent=2,
            )
        print(f"Не обработанные треки сохранены в {args.failed} — просто запустите скрипт ещё раз, чтобы повторить попытку")

    print(f"Результат сохранён в {args.output}")


if __name__ == "__main__":
    main()