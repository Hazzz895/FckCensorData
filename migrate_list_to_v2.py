def last_url_segment(url: str) -> str:
    return url.rstrip("/").rsplit("/", 1)[-1]


def find_target_storage(list_v2: dict) -> dict:
    matches = [
        s for s in list_v2.get("sources", [])
        if s.get("supportedVersion") == TARGET_SUPPORTED_VERSION
    ]
    if not matches:
        sys.exit(f'Не найден source с supportedVersion == "{TARGET_SUPPORTED_VERSION}" в list_v2.json')
    if len(matches) > 1:
        print(
            f'[!] Найдено {len(matches)} source с supportedVersion == "{TARGET_SUPPORTED_VERSION}", '
            f"использую первый",
            file=sys.stderr,
        )
    source = matches[0]
    storages = source.get("tracksStorages") or []
    if not storages:
        sys.exit("В целевом source отсутствует tracksStorages - добавлять данные некуда")
    if len(storages) > 1:
        print("[!] В целевом source несколько tracksStorages, использую первый", file=sys.stderr)
    return storages[0]


def already_migrated_ids(storage: dict) -> set:
    ids = set()
    for entry in storage.get("trackIds", []):
        if isinstance(entry, dict):
            ids.add(str(entry.get("id")))
        else:
            ids.add(str(entry))
    ids.update(storage.get("tracks", {}).keys())
    return ids


