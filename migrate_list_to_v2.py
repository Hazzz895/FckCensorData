def fetch_api_durations(client: YandexClient, ids, batch_size: int, retries: int = 2) -> dict:
    """Возвращает {id_str: durationMs} по данным Yandex Music API.
    Id, которые не удалось получить (сеть/бан/удалённый трек), просто отсутствуют
    в результате - для них позже будет использован явный durationMs."""
    ids = list(dict.fromkeys(ids))  # без дублей, с сохранением порядка
    durations: dict = {}
    total_batches = (len(ids) + batch_size - 1) // batch_size

    for batch_num, i in enumerate(range(0, len(ids), batch_size), start=1):
        batch = ids[i : i + batch_size]
        attempt = 0
        tracks = []
        while True:
            attempt += 1
            try:
                tracks = client.tracks(batch) or []
                break
            except YandexMusicError as e:
                if attempt > retries:
                    print(
                        f"[!] Yandex Music API: не удалось получить батч {batch_num}/{total_batches} "
                        f"после {attempt} попыток ({e}), эти {len(batch)} треков получат явный durationMs",
                        file=sys.stderr,
                    )
                    tracks = []
                    break
                time.sleep(1.5 * attempt)
            except Exception as e:
                # неожиданная ошибка (например обрыв сети) - не роняем весь скрипт
                if attempt > retries:
                    print(
                        f"[!] Yandex Music API: неожиданная ошибка на батче {batch_num}/{total_batches} ({e}), "
                        f"эти {len(batch)} треков получат явный durationMs",
                        file=sys.stderr,
                    )
                    tracks = []
                    break
                time.sleep(1.5 * attempt)

        for t in tracks:
            if t is None or t.duration_ms is None:
                continue
            durations[str(t.id)] = t.duration_ms

        print(f"Yandex Music API: батч {batch_num}/{total_batches}, всего получено {len(durations)}/{len(ids)}")

    return durations


