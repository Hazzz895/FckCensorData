def build_session() -> requests.Session:
    session = requests.Session()
    retry = Retry(
        total=3,
        backoff_factor=1.5,
        status_forcelist=[429, 500, 502, 503, 504],
        allowed_methods=["GET"],
    )
    adapter = HTTPAdapter(max_retries=retry, pool_maxsize=32)
    session.mount("https://", adapter)
    session.mount("http://", adapter)
    return session


_thread_local = threading.local()


def get_session() -> requests.Session:
    if not hasattr(_thread_local, "session"):
        _thread_local.session = build_session()
    return _thread_local.session


def duration_via_ffprobe(data: bytes, timeout: float):
    """Пробует получить длительность через ffprobe. Возвращает durationMs или None."""
    if not FFPROBE_PATH:
        return None
    tmp = tempfile.NamedTemporaryFile(suffix=".audio", delete=False)
    temp_path = tmp.name
    try:
        tmp.write(data)
        tmp.close()
        try:
            proc = subprocess.run(
                [FFPROBE_PATH, "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", temp_path],
                capture_output=True, text=True, timeout=timeout,
            )
        except (subprocess.TimeoutExpired, OSError) as e:
            print("Failed to run ffprobe", e)
            return None
    finally:
        if os.path.exists(temp_path):
            os.remove(temp_path)
    if proc.returncode != 0:
        print("Failed to run ffprobe", proc.stderr)
        return None
    try:
        seconds = float(proc.stdout.strip())
    except ValueError:
        print("Failed to parse ffprobe output", proc.stdout)
        return None
    if seconds <= 0:
        return None
    return round(seconds * 1000)


def fetch_duration_ms(url: str, timeout: float) -> int:
    session = get_session()
    resp = session.get(url, timeout=timeout)
    resp.raise_for_status()
    data = resp.content

    # 1) быстрый путь - mutagen (без внешних зависимостей)
    audio = mutagen.File(BytesIO(data)) # type: ignore
    if audio is not None and audio.info is not None:
        length_seconds = getattr(audio.info, "length", 0)
        if length_seconds and length_seconds > 0:
            return round(length_seconds * 1000)

    # 2) запасной путь - ffprobe (надёжнее для некоторых mp4/m4a контейнеров)
    duration_ms = duration_via_ffprobe(data, timeout)
    if duration_ms is not None:
        return duration_ms

    hint = "" if FFPROBE_PATH else " (установите ffmpeg, чтобы включить запасной способ определения длительности)"
    raise ValueError(f"не удалось определить длительность{hint}")


